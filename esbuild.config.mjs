import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { appendFileSync, copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/aleMode/obsidian-plugin-patchwork (MIT).
Licences of bundled third-party packages are at the end of this file.
*/
`;

const prod = process.argv[2] === 'production';

// Dev builds go straight into the test vault so Obsidian picks them up on reload.
const DEV_PLUGIN_DIR = 'test-vault/.obsidian/plugins/patchwork';
const outdir = prod ? '.' : DEV_PLUGIN_DIR;

const copyAssets = {
	name: 'copy-assets',
	setup(build) {
		build.onEnd(() => {
			if (prod) return;
			mkdirSync(outdir, { recursive: true });
			for (const file of ['manifest.json', 'styles.css']) {
				if (existsSync(file)) copyFileSync(file, join(outdir, file));
			}
		});
	},
};

/**
 * Only main.js reaches users, so the licences of the packages bundled into it (MIT and the like require
 * their notice in every copy) are appended to it. Read from the metafile, so the list follows the bundle.
 */
const licenseNotices = {
	name: 'license-notices',
	setup(build) {
		build.onEnd((result) => {
			if (!prod || !result.metafile) return;
			const pkgs = new Set();
			for (const input of Object.keys(result.metafile.inputs)) {
				const m = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
				if (m) pkgs.add(m[1]);
			}
			const notices = [...pkgs].sort().map((name) => {
				const dir = join('node_modules', name);
				const { version, license } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
				const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
				if (!file) throw new Error(`No licence file in ${dir}: add its notice by hand before releasing.`);
				return `${name}@${version} (${license})\n\n${readFileSync(join(dir, file), 'utf8').trim()}`;
			});
			if (notices.length === 0) return;
			const body = notices.join('\n\n----------------------------------------\n\n').replaceAll('*/', '* /');
			appendFileSync(join(outdir, 'main.js'), `\n/*! Bundled third-party packages and their licences:\n\n${body}\n*/\n`);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	define: { PW_DEV: String(!prod) },
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: join(outdir, 'main.js'),
	minify: prod,
	metafile: prod,
	plugins: [copyAssets, licenseNotices],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
