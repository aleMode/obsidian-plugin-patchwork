import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// Dev builds go straight into the test vault so Obsidian picks them up on reload.
const DEV_PLUGIN_DIR = 'test-vault/.obsidian/plugins/patchwork';
const outdir = prod ? '.' : DEV_PLUGIN_DIR;

const copyAssets = {
	name: 'copy-assets',
	setup(build) {
		build.onEnd(() => {
			if (prod) return;
			mkdirSync(outdir, { recursive: true });
			for (const file of ['manifest.json', 'styles.css']) {
				if (existsSync(file)) copyFileSync(file, join(outdir, file));
			}
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	define: { PW_DEV: String(!prod) },
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: join(outdir, 'main.js'),
	minify: prod,
	plugins: [copyAssets],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
